import { existsSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir, hostname } from 'node:os';
import { execFileSync } from 'node:child_process';

export interface DiscoveredShell {
  name: string;
  argv: string[];
  env?: Record<string, string>;
}

const PWSH_CWD_HOOK = join(
  dirname(fileURLToPath(import.meta.url)),
  'shell-init',
  'pwsh-cwd-hook.ps1',
);

const PWSH_ARGS = [
  '-NoLogo',
  '-NoExit',
  '-ExecutionPolicy', 'Bypass',
  '-File', PWSH_CWD_HOOK,
];

const UNIX_FALLBACK_PATHS = [
  '/bin/bash',
  '/usr/bin/bash',
  '/bin/zsh',
  '/usr/bin/zsh',
  '/bin/sh',
  '/usr/bin/sh',
  '/usr/bin/fish',
  '/usr/local/bin/fish',
  '/bin/dash',
  '/usr/bin/dash',
  '/bin/ksh',
  '/usr/bin/ksh',
  '/bin/tcsh',
  '/usr/bin/tcsh',
];

const UNIX_LOGIN_SHELLS = new Set(['bash', 'zsh', 'fish', 'ksh', 'tcsh', 'dash']);

// ── cwd reporting (OSC 7) ───────────────────────────────────────────────────
//
// Every shell mobitty launches is hooked to report its cwd, so the session
// list and file uploads never depend on a per-process probe (slow `lsof` on
// macOS, none at all on Windows). Hooks are installed after the user's own
// startup files wherever the shell allows, and shims live in
// {dataFolder}/shell-init, regenerated on server start.
//
// mobitty sets TERM_PROGRAM=mobitty (docs/done-design-terminal-env.md). On macOS
// that suppresses the stock zsh cwd hook: /etc/zshrc only sources
// /etc/zshrc_$TERM_PROGRAM, and Apple ships the emitter as
// /etc/zshrc_Apple_Terminal. With no replacement, no OSC 7 is ever emitted and
// the session list falls back to an `lsof` probe per session — which used to
// block the event loop on every connect and session switch.
// See docs/done-bug-lsof-cwd-blocks-connect.md.
//
// zsh has no environment-variable equivalent of `precmd`, so we point ZDOTDIR at
// a generated shim directory whose stubs forward to the user's real startup
// files and then install the hook. bash gets an --rcfile shim (BASH_RC_SHIM).
//
// Both encode `%` and spaces so the OSC 7 payload survives the client's
// percent-decoding (osc-cwd.ts).

const ZDOTDIR_ZSHENV = `# Generated by mobitty — do not edit; regenerated on server start.
# ZDOTDIR points at this directory so mobitty can install an OSC 7 cwd hook.
# Every stub forwards to the user's real startup file first.
: \${MOBITTY_USER_ZDOTDIR:=$HOME}
_mobitty_shim=$ZDOTDIR
[ -r "$MOBITTY_USER_ZDOTDIR/.zshenv" ] && . "$MOBITTY_USER_ZDOTDIR/.zshenv"
# The user's .zshenv may itself set ZDOTDIR — honour it as the new "real" dir,
# but re-assert ours so the remaining stubs still load.
[ "$ZDOTDIR" != "$_mobitty_shim" ] && MOBITTY_USER_ZDOTDIR=$ZDOTDIR
ZDOTDIR=$_mobitty_shim
unset _mobitty_shim
`;

const ZDOTDIR_ZPROFILE = `# Generated by mobitty — do not edit.
[ -r "\${MOBITTY_USER_ZDOTDIR:-$HOME}/.zprofile" ] && . "\${MOBITTY_USER_ZDOTDIR:-$HOME}/.zprofile"
`;

const ZDOTDIR_ZSHRC = `# Generated by mobitty — do not edit.
[ -r "\${MOBITTY_USER_ZDOTDIR:-$HOME}/.zshrc" ] && . "\${MOBITTY_USER_ZDOTDIR:-$HOME}/.zshrc"

# Emit OSC 7 before each prompt so the session list tracks the cwd without
# mobitty having to shell out to lsof. Under WSL the server is on Windows and
# needs a Windows path (see WSL_LAUNCH).
if autoload -Uz add-zsh-hook 2>/dev/null; then
  _mobitty_report_cwd() {
    emulate -L zsh
    local p=$PWD
    if [[ \${MOBITTY_CWD_STYLE-} == wsl ]]; then
      p=$(wslpath -m "$PWD" 2>/dev/null) || return
      [[ $p == //* ]] || p=/$p
    fi
    p=\${p//\\%/%25}
    printf '\\033]7;file://%s%s\\a' "\${HOST}" "\${p// /%20}"
  }
  add-zsh-hook precmd _mobitty_report_cwd
fi

# Hand ZDOTDIR back so anything later (.zlogin, user tooling) sees the real one.
ZDOTDIR="\${MOBITTY_USER_ZDOTDIR:-$HOME}"
`;

// bash: an env PROMPT_COMMAND is lost whenever a startup file assigns its own
// (common with git-prompt setups), so bash runs this file via --rcfile instead.
// It replays bash's login startup sequence — what `bash -l` would have read —
// then appends the hook, so nothing the user's files do can drop it. The cost:
// bash isn't flagged as a login shell (`shopt login_shell` is off, `logout`
// refuses; `exit` works). MOBITTY_CWD_STYLE picks the path form the server can
// use: `posix` (default) is $PWD; `msys` (Git Bash) and `wsl` produce Windows
// paths, `file://host/D:/dir` or `file://host//server/share/dir` — the forms
// parseOsc7 accepts on win32. Git Bash maps `/d/dir` without a fork and asks
// the `pwd -W` builtin for anything else (`/usr`, `/tmp`); WSL asks `wslpath`.
const BASH_RC_SHIM = `# Generated by mobitty — do not edit; regenerated on server start.
# bash runs this via --rcfile in place of ~/.bashrc so mobitty can install an
# OSC 7 cwd hook after the user's own startup files.
[ -r /etc/profile ] && . /etc/profile
if [ -r ~/.bash_profile ]; then . ~/.bash_profile
elif [ -r ~/.bash_login ]; then . ~/.bash_login
elif [ -r ~/.profile ]; then . ~/.profile
fi

__mobitty_report_cwd() {
  local p
  case \${MOBITTY_CWD_STYLE-} in
    msys)
      if [[ $PWD =~ ^/([A-Za-z])(/.*)?$ ]]; then
        p=/\${BASH_REMATCH[1]^}:\${BASH_REMATCH[2]:-/}
      else
        p=$(pwd -W) || return
        [[ $p == //* ]] || p=/$p
      fi ;;
    wsl)
      p=$(wslpath -m "$PWD" 2>/dev/null) || return
      [[ $p == //* ]] || p=/$p ;;
    *) p=$PWD ;;
  esac
  p=\${p//%/%25}
  printf '\\033]7;file://%s%s\\a' "$HOSTNAME" "\${p// /%20}"
}
# Append, so the user's hooks still see the command's $?. PROMPT_COMMAND may
# be an array (bash 5.1+); assigning a scalar would replace its first element.
if [[ $(declare -p PROMPT_COMMAND 2>/dev/null) == "declare -a"* ]]; then
  PROMPT_COMMAND+=(__mobitty_report_cwd)
else
  PROMPT_COMMAND=\${PROMPT_COMMAND:+$PROMPT_COMMAND$'\\n'}__mobitty_report_cwd
fi
`;

// POSIX sh family (dash, ksh, ash, sh) has no prompt hook, but reads the file
// named by $ENV at interactive startup and expands PS1 at every prompt. The
// shim sources the user's own ENV file, then prepends an OSC 7 emitter to PS1.
// Shells with command substitution in PS1 (ksh, bash-as-sh) write the sequence
// to /dev/tty so it adds no width to the prompt — their line editors would
// otherwise miscount it. dash only has parameter expansion and, as packaged,
// no line editor, so the sequence goes inline. That path is not percent-
// encoded: spaces decode fine, a literal `%` makes parseOsc7 reject the report.
const POSIX_ENV_SHIM = `# Generated by mobitty — do not edit; regenerated on server start.
# ENV points here so mobitty can install an OSC 7 cwd hook.
if [ -n "\${MOBITTY_USER_ENV-}" ] && [ -r "$MOBITTY_USER_ENV" ]; then
  . "$MOBITTY_USER_ENV"
fi
__mobitty_host=$(uname -n 2>/dev/null)
if [ -n "\${BASH_VERSION-}\${KSH_VERSION-}" ]; then
  PS1='$(printf "\\033]7;file://%s%s\\007" "$__mobitty_host" "$PWD" >/dev/tty)'"\${PS1-\\$ }"
else
  PS1="$(printf '\\033]7;file://%s' "$__mobitty_host")"'\${PWD}'"$(printf '\\007')\${PS1-\\$ }"
fi
`;

/** POSIX shells hooked through the ENV shim, mapped to the startup file they
 *  read when ENV is unset (so setting ENV doesn't hide it), or null. */
const POSIX_ENV_SHELLS: Record<string, string | null> = {
  sh: null,
  dash: null,
  ash: null,
  ksh: '.kshrc',
  ksh93: '.kshrc',
  mksh: '.mkshrc',
};

// WSL: wsl.exe normally runs the distro user's shell as a login shell. Instead
// it runs this launcher, which hooks bash and zsh with the same shims (reached
// through WSLENV's `/p` path translation) and execs any other shell as-is.
// Env set on the Windows side isn't visible inside WSL unless WSLENV lists it.
const WSL_LAUNCH =
  'case "$SHELL" in '
  + '*/bash) exec "$SHELL" --rcfile "$MOBITTY_BASH_RC" -i;; '
  + '*/zsh) export ZDOTDIR="$MOBITTY_ZDOTDIR"; exec "$SHELL" -l;; '
  + '*) exec "${SHELL:-/bin/sh}" -l;; '
  + 'esac';

/** cmd.exe: PROMPT is expanded at every prompt; `$P` is the drive and path. */
function cmdPrompt(): string {
  const prefix = `$E]7;file://${hostname()}/$P$E\\`;
  const user = process.env['PROMPT'] ?? '$P$G';
  // A server started from a mobitty cmd session already carries the prefix.
  return user.startsWith(prefix) ? user : prefix + user;
}

/** Appends `entries` (`NAME` or `NAME/flags`) to the inherited WSLENV, skipping
 *  names it already lists. */
function withWslenv(entries: string[]): string {
  const vars = (process.env['WSLENV'] ?? '').split(':').filter(Boolean);
  const names = new Set(vars.map(v => v.split('/')[0]));
  for (const entry of entries) {
    if (!names.has(entry.split('/')[0])) vars.push(entry);
  }
  return vars.join(':');
}

interface ShellInit {
  bashRc: string;
  zdotdir: string;
  posixEnv: string;
}

/** Writes every hook shim under `{dataFolder}/shell-init` and returns their
 *  paths, or null if they could not be created. */
function ensureShellInit(dataFolder: string): ShellInit | null {
  try {
    const dir = join(dataFolder, 'shell-init');
    const zdotdir = join(dir, 'zdotdir');
    mkdirSync(zdotdir, { recursive: true });
    writeFileSync(join(zdotdir, '.zshenv'), ZDOTDIR_ZSHENV);
    writeFileSync(join(zdotdir, '.zprofile'), ZDOTDIR_ZPROFILE);
    writeFileSync(join(zdotdir, '.zshrc'), ZDOTDIR_ZSHRC);
    // Deliberately no .zlogin: .zshrc restores ZDOTDIR, so zsh picks up the
    // user's own .zlogin from the real directory.
    const bashRc = join(dir, 'bashrc');
    writeFileSync(bashRc, BASH_RC_SHIM);
    const posixEnv = join(dir, 'env.sh');
    writeFileSync(posixEnv, POSIX_ENV_SHIM);
    return { bashRc, zdotdir, posixEnv };
  } catch {
    return null;
  }
}

/** Unix shell launch with its OSC 7 cwd hook installed, if it has one. */
function hookUnixShell(name: string, path: string, init: ShellInit | null): DiscoveredShell {
  if (name === 'pwsh') return { name, argv: [path, ...PWSH_ARGS] };
  const plain = { name, argv: UNIX_LOGIN_SHELLS.has(name) ? [path, '-i', '-l'] : [path] };
  if (!init) return plain;
  if (name === 'bash') return { name, argv: [path, '--rcfile', init.bashRc, '-i'] };
  if (name === 'zsh') {
    return {
      ...plain,
      env: { ZDOTDIR: init.zdotdir, MOBITTY_USER_ZDOTDIR: process.env['ZDOTDIR'] ?? homedir() },
    };
  }
  if (name in POSIX_ENV_SHELLS) {
    // A server started from a hooked session inherits ENV=shim; the user's
    // original is then in MOBITTY_USER_ENV. Sourcing the shim from itself
    // would recurse.
    const inherited = process.env['ENV'] === init.posixEnv ? process.env['MOBITTY_USER_ENV'] : process.env['ENV'];
    const defaultRc = POSIX_ENV_SHELLS[name];
    const userEnv = inherited ?? (defaultRc ? join(homedir(), defaultRc) : '');
    return { ...plain, env: userEnv ? { ENV: init.posixEnv, MOBITTY_USER_ENV: userEnv } : { ENV: init.posixEnv } };
  }
  // fish emits OSC 7 on its own. tcsh/csh have no env- or argv-driven startup
  // hook (no ENV/ZDOTDIR/--rcfile equivalent), so they fall back to
  // getProcessCwd.
  return plain;
}

/** Windows shell launch with its OSC 7 cwd hook installed. powershell/pwsh
 *  already carry theirs in PWSH_ARGS. */
function hookWindowsShell(name: string, exe: string, args: string[], init: ShellInit | null): DiscoveredShell {
  if (name === 'cmd') return { name, argv: [exe, ...args], env: { PROMPT: cmdPrompt() } };
  if (!init) return { name, argv: [exe, ...args] };
  if (name === 'git-bash') {
    return {
      name,
      argv: [exe, '--rcfile', init.bashRc.replace(/\\/g, '/'), '-i'],
      env: { MOBITTY_CWD_STYLE: 'msys' },
    };
  }
  if (name === 'wsl') {
    return {
      name,
      argv: [exe, '-e', 'sh', '-c', WSL_LAUNCH],
      env: {
        MOBITTY_BASH_RC: init.bashRc,
        MOBITTY_ZDOTDIR: init.zdotdir,
        MOBITTY_CWD_STYLE: 'wsl',
        WSLENV: withWslenv(['MOBITTY_BASH_RC/p', 'MOBITTY_ZDOTDIR/p', 'MOBITTY_CWD_STYLE']),
      },
    };
  }
  return { name, argv: [exe, ...args] };
}

function parseEtcShells(): string[] {
  try {
    const content = readFileSync('/etc/shells', 'utf-8');
    return content
      .split('\n')
      .map(line => line.trim())
      .filter(line => line.length > 0 && !line.startsWith('#'));
  } catch {
    return [];
  }
}

function discoverUnix(dataFolder?: string): DiscoveredShell[] {
  const seen = new Set<string>();
  const shells: DiscoveredShell[] = [];
  const init = dataFolder ? ensureShellInit(dataFolder) : null;

  const paths = parseEtcShells();
  const candidates = paths.length > 0 ? paths : UNIX_FALLBACK_PATHS;

  for (const shellPath of candidates) {
    if (!existsSync(shellPath)) continue;
    const name = basename(shellPath);
    if (seen.has(name)) continue;
    seen.add(name);
    shells.push(hookUnixShell(name, shellPath, init));
  }

  return shells;
}

function existsOnPath(cmd: string): boolean {
  try {
    execFileSync('where', [cmd], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

interface WindowsCandidate {
  name: string;
  cmd: string;
  absolutePaths: string[];
  args: string[];
}

const WINDOWS_CANDIDATES: WindowsCandidate[] = [
  { name: 'powershell', cmd: 'powershell.exe', absolutePaths: [], args: PWSH_ARGS },
  {
    name: 'pwsh',
    cmd: 'pwsh.exe',
    absolutePaths: ['C:\\Program Files\\PowerShell\\7\\pwsh.exe'],
    args: PWSH_ARGS,
  },
  { name: 'cmd', cmd: 'cmd.exe', absolutePaths: [], args: [] },
  {
    name: 'git-bash',
    cmd: '',
    absolutePaths: [
      'C:\\Program Files\\Git\\bin\\bash.exe',
      'C:\\Program Files (x86)\\Git\\bin\\bash.exe',
    ],
    args: ['-i', '-l'],
  },
  { name: 'wsl', cmd: 'wsl.exe', absolutePaths: [], args: [] },
];

function discoverWindows(dataFolder?: string): DiscoveredShell[] {
  const shells: DiscoveredShell[] = [];
  const init = dataFolder ? ensureShellInit(dataFolder) : null;

  for (const candidate of WINDOWS_CANDIDATES) {
    // Check absolute paths first
    let found = false;
    for (const absPath of candidate.absolutePaths) {
      if (existsSync(absPath)) {
        shells.push(hookWindowsShell(candidate.name, absPath, candidate.args, init));
        found = true;
        break;
      }
    }
    if (found) continue;

    // Check PATH
    if (candidate.cmd && existsOnPath(candidate.cmd)) {
      shells.push(hookWindowsShell(candidate.name, candidate.cmd, candidate.args, init));
    }
  }

  return shells;
}

export function discoverShells(dataFolder?: string): DiscoveredShell[] {
  if (process.platform === 'win32') {
    return discoverWindows(dataFolder);
  }
  return discoverUnix(dataFolder);
}
